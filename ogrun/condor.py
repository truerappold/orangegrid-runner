EVENT = re.compile(r'^(\d{3}) \((\d+)\.(\d+)\.(\d+)\)')


def read_log(path):
    """[(event code, text of that event)] from an HTCondor user log."""
    if not os.path.exists(path):
        return []
    events, cur = [], None
    with open(path, errors='replace') as f:
        for line in f:
            m = EVENT.match(line)
            if m:
                cur = [m.group(1), line]
                events.append(cur)
            elif cur is not None and not line.startswith('...'):
                cur[1] += line
    return [(c, t) for c, t in events]


def job_state(run_dir, job):
    """(state, detail): done | running | idle | held | failed | not submitted.

    Taken from the done marker and, for unfinished jobs, from the events
    after the latest submission in the job's HTCondor log.
    """
    if os.path.exists(os.path.join(job.output, DONE_MARKER)):
        return 'done', ''
    events = read_log(os.path.join(run_dir, 'logs', f'{job.name}.log'))
    last = max((i for i, (c, _t) in enumerate(events) if c == '000'), default=None)
    if last is None:
        return 'not submitted', ''
    state, detail = 'idle', ''
    for code, text in events[last:]:
        if code == '001':
            state = 'running'
        elif code in ('004', '013'):            # evicted / released: back to idle
            state = 'idle'
        elif code == '012':
            state = 'held'
            m = re.search(r'\n\s*(.+)', text)
            detail = m.group(1).strip() if m else ''
        elif code == '009':
            state, detail = 'failed', 'removed (condor_rm)'
        elif code == '005':
            m = re.search(r'return value (\d+)', text)
            state = 'failed'
            detail = f'exit code {m.group(1)}' if m else 'terminated abnormally'
    return state, detail


def in_queue(state):
    return state in ('idle', 'running', 'held')


def condor_submit(run_dir):
    """Submit job.sub; returns (cluster id or None, condor_submit's output)."""
    exe = shutil.which('condor_submit')
    if not exe:
        raise RuntimeError('condor_submit not found -- run this on the OrangeGrid '
                           'login node, or use --no-submit to only write the files')
    p = subprocess.run([exe, 'job.sub'], cwd=run_dir, capture_output=True, text=True)
    out = (p.stdout + p.stderr).strip()
    if p.returncode != 0:
        raise RuntimeError(f'condor_submit failed:\n{out}')
    m = re.search(r'submitted to cluster (\d+)', out)
    return (m.group(1) if m else None), out
