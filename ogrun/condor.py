"""Everything HTCondor: the files of a run, submitting, reading job states.

A run directory holds
    run.json        the options it was created with (ogrun resubmit reuses them)
    jobs.tsv        index, name, output folder and the full command of every job
    queue.txt       the jobs of the latest submission (HTCondor reads this)
    run_job.sh      the script each job runs (activate env, check GPU, run, mark done)
    job.sub         the HTCondor submit description
    logs/<name>.out/.err/.log   per job

A job is *done* when its output folder contains .ogrun_done, which run_job.sh
writes only after the command exits 0.  So a crashed, evicted or half-written
job is never mistaken for a finished one, and resubmitting skips only real
successes.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import shutil
import subprocess

DONE_MARKER = '.ogrun_done'
DEFAULT_EXCLUDE = ('CRUSH-NODE-10-5-5-5',)   # broken GPU node (lab experience)

RUN_JOB_SH = r'''#!/bin/bash
# Generated by ogrun for run "@@RUN_NAME@@".  One job:  run_job.sh INDEX
# No "set -u": conda's activate scripts read unset variables and abort.
set -o pipefail
IDX="$1"
RUN_DIR=@@RUN_DIR@@
LINE=$(awk -F'\t' -v i="$IDX" '$1 == i { print; exit }' "$RUN_DIR/jobs.tsv")
if [ -z "$LINE" ]; then echo "ogrun: no job $IDX in $RUN_DIR/jobs.tsv"; exit 2; fi
NAME=$(printf '%s\n' "$LINE" | cut -f2)
OUT=$(printf '%s\n' "$LINE" | cut -f3)
CMD=$(printf '%s\n' "$LINE" | cut -f4-)
echo "ogrun job $IDX ($NAME) on $(hostname), $(date)"
mkdir -p "$OUT" || exit 2
if [ -e "$OUT/@@DONE@@" ] && [ "${OGRUN_FORCE:-0}" != "1" ]; then
    echo "ogrun: already done ($OUT/@@DONE@@) -- nothing to do"
    exit 0
fi
rm -f "$OUT/@@DONE@@"
@@ENV_EXPORTS@@
CONDA_ENV=@@CONDA_ENV@@
if [ -n "$CONDA_ENV" ]; then
    eval "$(@@CONDA_BASE@@/bin/conda shell.bash hook)" \
        && conda activate "$CONDA_ENV" \
        || { echo "ogrun: could not activate conda env $CONDA_ENV"; exit 2; }
fi
GPU_CHECK=@@GPU_CHECK@@
if [ -n "$GPU_CHECK" ]; then
    # exit 3 = this machine's GPU is unusable; HTCondor retries elsewhere
    bash -c "$GPU_CHECK" || { echo "ogrun: no usable GPU on $(hostname)"; exit 3; }
    nvidia-smi --query-gpu=name,memory.total --format=csv,noheader 2>/dev/null
fi
cd @@WORKDIR@@ || exit 2
export OGRUN_JOB_INDEX="$IDX" OGRUN_JOB_NAME="$NAME" OGRUN_OUTPUT="$OUT"
echo "ogrun: running: $CMD"
START=$(date +%s)
bash -c "$CMD"
STATUS=$?
SECS=$(( $(date +%s) - START ))
if [ $STATUS -eq 0 ]; then
    printf 'host=%s\nseconds=%s\nfinished=%s\n' "$(hostname)" "$SECS" \
        "$(date '+%Y-%m-%dT%H:%M:%S')" > "$OUT/@@DONE@@.part" \
        && mv "$OUT/@@DONE@@.part" "$OUT/@@DONE@@"
fi
echo "ogrun: exit $STATUS after $SECS s, $(date)"
exit $STATUS
'''


def requirements(cfg):
    parts = []
    if cfg.get('gpu'):
        parts += ['TotalGPUS > 0', f"(CUDADriverVersion >= {cfg['cuda_driver']})"]
        if cfg.get('gpu_memory_mb'):
            parts.append(f"(CUDAGlobalMemoryMb >= {cfg['gpu_memory_mb']})")
    parts += [f'(Machine != "{m}")' for m in cfg.get('exclude_machines') or ()]
    if cfg.get('requirements'):
        parts.append(f"({cfg['requirements']})")
    return ' && '.join(parts)


def submit_description(run_dir, cfg):
    env = ['HOME=$ENV(HOME)'] + [f'{k}={v}' for k, v in (cfg.get('env') or {}).items()]
    if cfg.get('force'):
        env.append('OGRUN_FORCE=1')
    lines = [
        f"# Generated by ogrun for run \"{cfg['name']}\"",
        'universe             = vanilla',
        # bash runs the script, so it never needs to be executable (copying
        # files from a Mac or a USB drive often drops the executable bit)
        'executable           = /bin/bash',
        'transfer_executable  = false',
        f'arguments            = {run_dir}/run_job.sh $(job)',
        f"initialdir           = {cfg['workdir']}",
        f'environment          = "{" ".join(env)}"',
        f"request_cpus         = {cfg['cpus']}",
        f"request_memory       = {cfg['memory']}",
        f"request_disk         = {cfg['disk']}",
    ]
    if cfg.get('gpu'):
        lines += ['request_gpus         = 1', '+request_gpus        = 1']
    req = requirements(cfg)
    if req:
        lines.append(f'requirements         = {req}')
    lines += [
        f"max_retries          = {cfg['max_retries']}",
        f'output               = {run_dir}/logs/$(name).out',
        f'error                = {run_dir}/logs/$(name).err',
        f'log                  = {run_dir}/logs/$(name).log',
        f'queue job,name from {run_dir}/queue.txt',
        '',
    ]
    return '\n'.join(lines)


def check_path(p, what):
    if any(c.isspace() for c in p) or ',' in p:
        raise ValueError(f'{what} {p!r} contains a space or comma, which HTCondor '
                         f'cannot handle in submit files -- use a path without')


def write_run(run_dir, jobs, cfg, to_submit):
    """Write every file of the run; to_submit = the jobs for queue.txt."""
    check_path(run_dir, 'run directory')
    check_path(cfg['workdir'], 'working directory')
    os.makedirs(os.path.join(run_dir, 'logs'), exist_ok=True)
    with open(os.path.join(run_dir, 'run.json'), 'w') as f:
        json.dump(cfg, f, indent=2)
    with open(os.path.join(run_dir, 'jobs.tsv'), 'w') as f:
        for j in jobs:
            f.write(f'{j.index}\t{j.name}\t{j.output}\t{j.command}\n')
    with open(os.path.join(run_dir, 'queue.txt'), 'w') as f:
        for j in to_submit:
            f.write(f'{j.index},{j.name}\n')
    exports = '\n'.join(f'export {k}={shlex.quote(str(v))}'
                        for k, v in (cfg.get('env') or {}).items())
    script = (RUN_JOB_SH
              .replace('@@RUN_NAME@@', cfg['name'])
              .replace('@@RUN_DIR@@', shlex.quote(run_dir))
              .replace('@@DONE@@', DONE_MARKER)
              .replace('@@ENV_EXPORTS@@', exports)
              .replace('@@CONDA_ENV@@', shlex.quote(cfg.get('conda_env') or ''))
              .replace('@@CONDA_BASE@@', shlex.quote(cfg.get('conda_base') or ''))
              .replace('@@GPU_CHECK@@', shlex.quote(cfg.get('gpu_check') or ''))
              .replace('@@WORKDIR@@', shlex.quote(cfg['workdir'])))
    path = os.path.join(run_dir, 'run_job.sh')
    with open(path, 'w') as f:
        f.write(script)
    os.chmod(path, 0o755)
    with open(os.path.join(run_dir, 'job.sub'), 'w') as f:
        f.write(submit_description(run_dir, cfg))


